function bindReveal(){
  const els=[...document.querySelectorAll('[data-reveal]')];if(!els.length)return;
  if(!('IntersectionObserver'in window)){els.forEach(el=>el.classList.add('is-visible'));return;}
  const io=new IntersectionObserver(entries=>entries.forEach(entry=>{if(entry.isIntersecting){entry.target.classList.add('is-visible');io.unobserve(entry.target);}}),{threshold:.07,rootMargin:'0px 0px -4%'});els.forEach(el=>io.observe(el));
}
