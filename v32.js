function renderContact(c){
  const root=document.querySelector('#contactContent');if(!root)return;
  const head=Array.isArray(c.headline)?c.headline:['LET’S TALK','ABOUT SYSTEMS.'];
  const links=[
    ['MAIL',`mailto:${c.email||''}`,ICONS.mail],['GITHUB',c.github,ICONS.github],['LINKEDIN',c.linkedin,ICONS.linkedin],['BLOG',c.blog,ICONS.blog]
  ].filter(x=>x[1]&&!x[1].endsWith(':'));
  root.innerHTML=`<div class="contact-kicker">CONTACT / OPEN FOR CONVERSATION</div><h2><span>${esc(head[0]||'')}</span><span>${esc(head[1]||'')}</span></h2><div class="contact-actions">${links.map(([label,href,icon])=>`<a class="contact-icon-link" href="${esc(href)}" ${href.startsWith('mailto:')?'':'target="_blank" rel="noreferrer"'}><span class="contact-icon">${icon}</span><span>${label}</span><b>↗</b></a>`).join('')}</div>`;
}

function cleanupProjectTransition(){
  document.querySelectorAll('.transition-clone,.transition-shade').forEach(el=>el.remove());
  document.documentElement.classList.remove('project-transition-active');
  document.querySelectorAll('.project-card.is-leaving,.project-card.is-return-target').forEach(el=>el.classList.remove('is-leaving','is-return-target'));
}
function warmProjectPage(link){
  if(!link||link.dataset.prefetched)return;link.dataset.prefetched='1';
  try{fetch(link.href,{cache:'force-cache',credentials:'same-origin'}).catch(()=>{});}catch{}
}
function bindProjectTransitions(scope=document){
  scope.querySelectorAll('.project-transition-link').forEach(link=>{
    if(link.dataset.transitionBound)return;link.dataset.transitionBound='1';
    link.addEventListener('pointerenter',()=>warmProjectPage(link),{once:true});
    link.addEventListener('focus',()=>warmProjectPage(link),{once:true});
    link.addEventListener('click',event=>{
      if(event.defaultPrevented||event.button!==0||event.metaKey||event.ctrlKey||event.shiftKey||event.altKey)return;
      const image=link.querySelector('.project-card-image');if(!image)return;
      if(matchMedia('(prefers-reduced-motion: reduce)').matches)return;
      event.preventDefault();cleanupProjectTransition();warmProjectPage(link);
      const rect=image.getBoundingClientRect();
      const clone=image.cloneNode(true);clone.removeAttribute('style');clone.removeAttribute('loading');clone.removeAttribute('draggable');clone.className='transition-clone';
      Object.assign(clone.style,{left:`${rect.left}px`,top:`${rect.top}px`,width:`${rect.width}px`,height:`${rect.height}px`,borderRadius:getComputedStyle(image).borderRadius||'12px'});
      const shade=document.createElement('div');shade.className='transition-shade';
      document.documentElement.classList.add('project-transition-active');link.closest('.project-card')?.classList.add('is-leaving');
      document.body.append(shade,clone);
      clone.getBoundingClientRect();
      requestAnimationFrame(()=>requestAnimationFrame(()=>{
        shade.classList.add('is-on');clone.classList.add('is-expanding');
        Object.assign(clone.style,{left:'0px',top:'0px',width:'100vw',height:'100vh',borderRadius:'0px'});
      }));
      const slug=link.dataset.project||'';
      const transitionImage=image.currentSrc||image.src;
      try{
        sessionStorage.setItem('portfolioTransitionTarget',slug);
        sessionStorage.setItem('portfolioTransitionImage',transitionImage);
        sessionStorage.setItem('portfolioTransitionOrigin',location.href);
      }catch{}
      setTimeout(()=>{location.assign(link.href)},675);
    });
  });
}
let reverseTransitionRunning=false;
async function playReverseProjectTransition(){
  if(reverseTransitionRunning)return false;
  let data=null;
  try{const raw=sessionStorage.getItem('portfolioReverseTransition');if(raw)data=JSON.parse(raw)}catch{}
  if(!data?.slug||!data?.image)return false;
  const safeSlug=window.CSS?.escape?CSS.escape(data.slug):data.slug.replace(/[^a-zA-Z0-9_-]/g,'');
  const link=document.querySelector(`.project-transition-link[data-project="${safeSlug}"]`);
  const image=link?.querySelector('.project-card-image');
  if(!image)return false;
  reverseTransitionRunning=true;
  const rect=image.getBoundingClientRect();
  const card=link.closest('.project-card');card?.classList.add('is-return-target');
  const clone=document.createElement('img');clone.src=data.image;clone.alt='';clone.className='transition-clone transition-return-clone';
  Object.assign(clone.style,{left:'0px',top:'0px',width:'100vw',height:'100vh',borderRadius:'0px'});
  document.body.appendChild(clone);
  try{await clone.decode()}catch{}
  document.documentElement.classList.remove('reverse-arrival-pending');
  document.documentElement.style.removeProperty('--transition-image');
  clone.getBoundingClientRect();
  requestAnimationFrame(()=>requestAnimationFrame(()=>Object.assign(clone.style,{left:`${rect.left}px`,top:`${rect.top}px`,width:`${rect.width}px`,height:`${rect.height}px`,borderRadius:getComputedStyle(image).borderRadius||'12px'})));
  setTimeout(()=>{
    clone.classList.add('is-fading');
    setTimeout(()=>{clone.remove();card?.classList.remove('is-return-target')},150);
    try{sessionStorage.removeItem('portfolioReverseTransition');sessionStorage.removeItem('portfolioTransitionImage');sessionStorage.removeItem('portfolioTransitionTarget');sessionStorage.removeItem('portfolioTransitionOrigin')}catch{}
    reverseTransitionRunning=false;
  },670);
  return true;
}
