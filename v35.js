async function renderJournalPreview(){
  const devRoot=document.querySelector('#journalDevlog');const critiqueRoot=document.querySelector('#journalCritique');if(!devRoot&&!critiqueRoot)return;
  let posts=[];try{const response=await fetch(ROOT+'assets/data/journal.json',{cache:'no-store'});if(!response.ok)throw new Error('journal');const data=await response.json();posts=data.posts||data;}catch{posts=JOURNAL_FALLBACK;}
  const groupOf=p=>String(p?.group||normalizeJournalGroup(p?.category||'')).toUpperCase();
  const devlogs=posts.filter(p=>groupOf(p)==='WORK').slice(0,3);
  const critiques=posts.filter(p=>groupOf(p)==='CRITIQUE').slice(0,3);
  if(devRoot){devRoot.dataset.count=String(devlogs.length);devRoot.innerHTML=devlogs.length?devlogs.map(journalCard).join(''):'<div class="journal-empty journal-empty-wide">아직 공개된 DEVLOG가 없습니다.</div>';}
  if(critiqueRoot){critiqueRoot.dataset.count=String(critiques.length);critiqueRoot.innerHTML=critiques.length?critiques.map(critiqueCard).join(''):'<div class="journal-empty">최근 CRITIQUE가 없습니다.</div>';}
}

